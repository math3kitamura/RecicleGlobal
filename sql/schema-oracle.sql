-- Aviso: este script nao e idempotente; nao execute novamente se as tabelas ja existem.

CREATE SEQUENCE RG_USUARIO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE RG_INSTITUICAO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE RG_DOACAO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE RG_SOLICITACAO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE RG_USUARIO (
    ID NUMBER(19,0) NOT NULL,
    NOME VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT PK_RG_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_RG_USUARIO_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE RG_INSTITUICAO (
    ID NUMBER(19,0) NOT NULL,
    NOME VARCHAR2(120 CHAR) NOT NULL,
    DESCRICAO VARCHAR2(500 CHAR),
    BAIRRO VARCHAR2(100 CHAR) NOT NULL,
    LATITUDE NUMBER(10,7) NOT NULL,
    LONGITUDE NUMBER(10,7) NOT NULL,
    CONSTRAINT PK_RG_INSTITUICAO PRIMARY KEY (ID)
);

CREATE TABLE RG_DOACAO (
    ID NUMBER(19,0) NOT NULL,
    USUARIO_ID NUMBER(19,0) NOT NULL,
    CATEGORIA VARCHAR2(20 CHAR) NOT NULL,
    TITULO VARCHAR2(120 CHAR) NOT NULL,
    DESCRICAO VARCHAR2(500 CHAR),
    QUANTIDADE NUMBER(10,0) NOT NULL,
    DATA_VALIDADE DATE,
    BAIRRO VARCHAR2(100 CHAR) NOT NULL,
    LATITUDE NUMBER(10,7) NOT NULL,
    LONGITUDE NUMBER(10,7) NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    CRIADA_EM TIMESTAMP NOT NULL,
    CONSTRAINT PK_RG_DOACAO PRIMARY KEY (ID),
    CONSTRAINT FK_RG_DOACAO_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES RG_USUARIO(ID),
    CONSTRAINT CK_RG_DOACAO_CATEGORIA CHECK (CATEGORIA IN ('ALIMENTO','ROUPA')),
    CONSTRAINT CK_RG_DOACAO_STATUS CHECK (STATUS IN ('DISPONIVEL','RESERVADA','CONCLUIDA')),
    CONSTRAINT CK_RG_DOACAO_QTD CHECK (QUANTIDADE > 0)
);

CREATE TABLE RG_SOLICITACAO (
    ID NUMBER(19,0) NOT NULL,
    DOACAO_ID NUMBER(19,0) NOT NULL,
    INTERESSADO_ID NUMBER(19,0) NOT NULL,
    STATUS VARCHAR2(20 CHAR) NOT NULL,
    CRIADA_EM TIMESTAMP NOT NULL,
    CONSTRAINT PK_RG_SOLICITACAO PRIMARY KEY (ID),
    CONSTRAINT FK_RG_SOL_DOACAO FOREIGN KEY (DOACAO_ID) REFERENCES RG_DOACAO(ID),
    CONSTRAINT FK_RG_SOL_USUARIO FOREIGN KEY (INTERESSADO_ID) REFERENCES RG_USUARIO(ID),
    CONSTRAINT CK_RG_SOL_STATUS CHECK (STATUS IN ('PENDENTE','ACEITA','RECUSADA','CANCELADA','CONCLUIDA'))
);

CREATE INDEX IX_RG_SOL_DOACAO ON RG_SOLICITACAO (DOACAO_ID);
CREATE INDEX IX_RG_DOACAO_USUARIO ON RG_DOACAO (USUARIO_ID);

COMMIT;
